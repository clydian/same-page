import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { readFileSync } from 'node:fs';
import { expect, test } from 'vitest';
const base = 'vendor/clydian-chorus-player-0.1.19-samepage.2.tgz';
const current = 'vendor/clydian-chorus-player-0.1.19-samepage.3.tgz';
const members = file => execFileSync('tar', ['-tzf', file], { encoding: 'utf8' }).trim().split('\n').filter(n => !n.endsWith('/')).sort();
const content = (file, name) => execFileSync('tar', ['-xOf', file, name]);
const hash = bytes => createHash('sha256').update(bytes).digest('hex');
test('source-direction player preserves all non-display runtime seams including AudioWorklet session cancellation and practice extensions', () => {
  const old = members(base), now = members(current);
  expect(now.filter(n => !old.includes(n))).toEqual(['package/dist/source-text-declarations.js', 'package/dist/source-wedge-declarations.js']);
  expect(old.filter(n => !now.includes(n))).toEqual([]);
  const changed = old.filter(n => !content(base, n).equals(content(current, n)));
  expect(changed).toEqual(['package/dist/engine.js', 'package/dist/musicxml-direction-timing.d.ts', 'package/dist/musicxml-direction-timing.js', 'package/package.json']);
  const manifest = JSON.parse(readFileSync('vendor/chorus-player-0.1.19-samepage.3.manifest.json'));
  expect(hash(readFileSync(base))).toBe(manifest.baseArtifactSha256);
  expect(hash(readFileSync(current))).toBe(manifest.artifactSha256);
  expect(hash(readFileSync('vendor/patches/chorus-player-0.1.19-samepage.3-source-directions.patch'))).toBe(manifest.patchSha256);
});
test('native exact peer and full source archive preserve existing AudioWorklet source and MPL attribution', () => {
  const file = 'vendor/coderline-alphatab-1.8.4-samepage.4.tgz';
  const metadata = JSON.parse(content(file, 'package/package.json'));
  const manifest = JSON.parse(readFileSync('vendor/alphatab-1.8.4-samepage.4.manifest.json'));
  const before = JSON.parse(readFileSync('vendor/alphatab-1.8.4-samepage.3.manifest.json'));
  const audio = 'packages/alphatab/src/platform/javascript/AlphaSynthAudioWorkletOutput.ts';
  expect(manifest.modifiedSource[audio]).toBeDefined();
  expect(manifest.modifiedSource[audio]).toBe(before.modifiedSource[audio]);
  expect(hash(readFileSync(file))).toBe(manifest.artifactSha256);
  expect(hash(content(file, `package/${manifest.sourceArchive}`))).toBe(manifest.sourceSha256);
  expect(metadata.samePageSource.sourceCommit).toBe(manifest.sourceCommit);
  expect(JSON.parse(content(current, 'package/package.json')).peerDependencies['@coderline/alphatab']).toBe(metadata.version);
  expect(content(file, 'package/LICENSE').toString()).toContain('Mozilla Public License');
});
