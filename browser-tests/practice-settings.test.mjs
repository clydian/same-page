import assert from 'node:assert/strict';
import test from 'node:test';
import { mkdir } from 'node:fs/promises';
import { chromium, webkit, expect } from '@playwright/test';
import { startStorageFixture } from './storage-fixture.mjs';
import { musicXmlFixture } from './musicxml-fixture.mjs';

for (const [engine, type] of [['chromium', chromium], ['webkit', webkit]]) test(`XML settings progressive disclosure and feature help (${engine})`, {timeout:180000}, async t => {
 const fixture=await startStorageFixture({authenticated:true,previewEntry:false});let browser;
 t.after(async()=>{try{await browser?.close();}finally{await fixture.stop();}});
 browser=await type.launch(engine==='chromium'&&process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE_PATH?{executablePath:process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE_PATH}:{});
 const context=await browser.newContext({viewport:{width:390,height:844},serviceWorkers:'block',hasTouch:true});
 await context.addInitScript(()=>localStorage.setItem('reader-gesture-hint-seen','true'));
 await context.request.post(fixture.origin+'/api/auth/sign-in/email',{headers:{origin:fixture.origin},data:{email:fixture.accounts[0].email,password:fixture.accounts[0].password}});
 const bytes=musicXmlFixture(16),id=crypto.randomUUID();
 assert.equal((await context.request.post(`${fixture.origin}/api/choirs/${fixture.choirId}/scores/${fixture.scoreId}/attachments/${id}/file?name=rhythm.xml&size=${bytes.length}`,{data:bytes,headers:{'content-length':String(bytes.length)}})).status(),201);
 const page=await context.newPage(),errors=[];page.on('pageerror',error=>errors.push(error.message));
 await page.goto(`${fixture.origin}/choirs/${fixture.choirId}/scores/${fixture.scoreId}`);
 await expect(page.locator('canvas[data-pdf-canvas-active]').first()).toBeVisible({timeout:20000});
 await page.locator('.page-reader__viewport').click({position:{x:180,y:200}});
 await page.getByRole('button',{name:'练习谱',exact:true}).click();await page.getByRole('button',{name:'rhythm.xml',exact:true}).click();
 const bar=page.getByTestId('musicxml-player');
 await expect(bar.getByRole('button',{name:'播放',exact:true})).toBeEnabled({timeout:60000});
 await mkdir('artifacts/verification/practice-settings',{recursive:true});
 await bar.getByRole('button',{name:'练习设置',exact:true}).click();
 const settings=page.getByRole('dialog',{name:'练习设置',exact:true});
 await expect(settings.getByRole('switch',{name:'声部关注',exact:true})).not.toBeChecked();
 await expect(settings.getByLabel('关注声部',{exact:true})).toHaveCount(0);
 for(const [name,width,height] of [['mobile',390,844],['small-mobile',320,740],['desktop',1440,1000]]) {
  await page.setViewportSize({width,height});
  await expect(settings).toBeVisible();
  const bounds=await settings.boundingBox();assert.ok(bounds.x>=0 && bounds.x+bounds.width<=width);
  await page.screenshot({path:`artifacts/verification/practice-settings/${engine}-${name}-overview.png`});
  const helpColumns=await settings.locator('.practice-setting-row > .practice-help-button').evaluateAll(buttons=>buttons.map(button=>button.getBoundingClientRect().x));
  assert.ok(helpColumns.every(x=>Math.abs(x-helpColumns[0])<1),'help buttons share one column');
  await settings.getByRole('button',{name:'声部混音',exact:true}).click();
  await expect(settings.getByRole('slider',{name:'Alto 音量',exact:true})).toBeVisible();
  assert.ok(await settings.evaluate(element=>element.scrollWidth<=element.clientWidth),'expanded mixer does not overflow');
  const faders=await settings.locator('.practice-part-volume input').evaluateAll(inputs=>inputs.map(input=>input.getBoundingClientRect().width));
  assert.ok(faders.every(width=>width>=90),'each mixer fader has enough space for touch adjustment');
  await page.screenshot({path:`artifacts/verification/practice-settings/${engine}-${name}-mixer.png`});
  await settings.getByRole('button',{name:'声部混音',exact:true}).click();
 }
 await page.setViewportSize({width:390,height:844});
 await settings.getByRole('switch',{name:'声部关注',exact:true}).locator('xpath=ancestor::label').click();
 await expect(settings.getByLabel('关注声部',{exact:true})).toBeVisible();
 await settings.getByRole('slider',{name:'其他声部音量',exact:true}).fill('0.2');
 await page.screenshot({path:`artifacts/verification/practice-settings/${engine}-mobile-focus.png`});
 await settings.getByRole('button',{name:'声部关注说明',exact:true}).tap();
 await expect(page.getByRole('dialog',{name:'声部关注说明',exact:true})).toBeVisible();
 await expect(settings.getByRole('switch',{name:'声部关注',exact:true})).toBeChecked();
 await page.screenshot({path:`artifacts/verification/practice-settings/${engine}-mobile-help.png`});
 await page.getByRole('button',{name:'知道了',exact:true}).click();
 await expect(settings).toBeVisible();
 await settings.getByRole('switch',{name:'声部关注',exact:true}).locator('xpath=ancestor::label').click();
 await settings.getByRole('switch',{name:'片段循环',exact:true}).locator('xpath=ancestor::label').click();
 await expect(bar.getByRole('button',{name:'练习设置',exact:true})).toHaveAttribute('data-loop','true');
 await expect(settings.getByRole('slider',{name:/循环起点/})).toHaveValue('0');
 await expect(settings.getByRole('slider',{name:/循环终点/})).toHaveValue('15');
 await expect(settings.getByRole('button',{name:/应用范围|取消调整|调整范围/})).toHaveCount(0);
 await page.screenshot({path:`artifacts/verification/practice-settings/${engine}-mobile-loop.png`});
 await settings.getByRole('switch',{name:'片段循环',exact:true}).locator('xpath=ancestor::label').click();
 await expect(bar.getByRole('button',{name:'练习设置',exact:true})).not.toHaveAttribute('data-loop','true');
 await settings.getByRole('button',{name:'关闭练习设置',exact:true}).click();
 await bar.getByRole('button',{name:'练习设置',exact:true}).click();
 await settings.getByRole('switch',{name:'片段循环',exact:true}).locator('xpath=ancestor::label').click();
 await expect(settings.getByRole('slider',{name:/循环终点/})).toBeVisible();
 await expect(bar.getByRole('button',{name:'练习设置',exact:true})).toHaveAttribute('data-loop','true');
 assert.deepEqual(errors,[]);
});
